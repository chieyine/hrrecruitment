import { prisma } from '@/lib/prisma'
import { requirePermission, authzResponse, AuthzError } from '@/lib/authz'
import { logAudit } from '@/lib/audit'
import { rowsToCsv, safeExportName, zipEntries } from '@/lib/export-files'

export const dynamic = 'force-dynamic'

export async function GET(_: Request, context: { params: Promise<{ id: string }> }) {
  const params = await context.params
  try {
    const user = await requirePermission('report.export')
    const vacancy = await prisma.vacancy.findUnique({
      where: { id: params.id },
      include: {
        department: true,
        project: true,
        category: true,
        dutyStation: true,
        questions: true,
        requiredDocuments: true,
        assessments: true,
        applications: {
          include: {
            candidate: { include: { user: { select: { email: true } } } },
            stageHistory: true,
            candidateAssessments: { include: { assessment: true } },
            interviews: { include: { panelMembers: true, panelSubmissions: true } },
            referees: { include: { requests: { include: { response: { select: { outcome: true } } } } } },
            selectionDecisions: true,
            offers: true,
            preboardings: { include: { readinessChecks: true } },
            resumptionRecord: true,
            erpTransferRecord: true,
          },
        },
      },
    })
    if (!vacancy) throw new AuthzError('Vacancy not found', 404)
    const generatedAt = new Date().toISOString()
    const applications = vacancy.applications
    const files = [
      {
        name: 'README.txt',
        data: `FRAD vacancy recruitment file\nVacancy: ${vacancy.referenceNumber} - ${vacancy.title}\nGenerated: ${generatedAt}\nGenerated by: ${user.email}\nClassification: INTERNAL - PERSONAL DATA\n\nThis point-in-time pack contains the vacancy specification and recruitment registers. Candidate document contents, restricted notes and confidential reference comments are excluded.\n`,
      },
      {
        name: '01-vacancy-summary.csv',
        data: rowsToCsv([
          {
            Reference: vacancy.referenceNumber,
            Title: vacancy.title,
            Department: vacancy.department.name,
            Project: vacancy.project?.name || '',
            Category: vacancy.category?.name || '',
            'Duty station': vacancy.dutyStation.name,
            Positions: vacancy.numberOfPositions,
            'Contract type': vacancy.contractType,
            Status: vacancy.status,
            Opening: vacancy.openingAt,
            Closing: vacancy.closingAt,
            Owner: vacancy.ownerUserId,
            Summary: vacancy.summary,
            Responsibilities: vacancy.responsibilities,
            'Essential qualifications': vacancy.essentialQualifications,
          },
        ]),
      },
      {
        name: '02-application-questions.csv',
        data: rowsToCsv(
          vacancy.questions.map((item) => ({
            Order: item.displayOrder + 1,
            Type: item.fieldType,
            Question: item.label,
            Required: item.required,
            Help: item.helpText || '',
            Condition: item.conditionJson || '',
          }))
        ),
      },
      {
        name: '03-required-documents.csv',
        data: rowsToCsv(
          vacancy.requiredDocuments.map((item) => ({
            Type: item.documentType,
            Required: item.required,
            'Allowed file types': item.allowedFileTypes,
            'Maximum bytes': item.maximumFileSize,
            'Expiry required': item.expiryRequired,
          }))
        ),
      },
      {
        name: '04-applications.csv',
        data: rowsToCsv(
          applications.map((item) => ({
            'Application ID': item.id,
            Candidate: `${item.candidate.legalFirstName} ${item.candidate.lastName}`,
            Email: item.candidate.user.email,
            'Internal stage': item.internalStatus,
            'Candidate-visible status': item.candidateVisibleStatus,
            Submitted: item.submittedAt,
            'Screening score': item.screeningScore ?? '',
            'Assessment score': item.assessmentScore ?? '',
            'Interview score': item.interviewScore ?? '',
            'Final score': item.finalScore ?? '',
            Recommendation: item.recommendation || '',
            'Reference status': item.referenceStatus,
            'Offer status': item.offerStatus || '',
            'Preboarding status': item.preboardingStatus || '',
          }))
        ),
      },
      {
        name: '05-stage-history.csv',
        data: rowsToCsv(
          applications.flatMap((application) =>
            application.stageHistory.map((item) => ({
              Candidate: `${application.candidate.legalFirstName} ${application.candidate.lastName}`,
              From: item.fromStatus,
              To: item.toStatus,
              Reason: item.reason || '',
              At: item.createdAt,
              'Changed by': item.changedBy,
            }))
          )
        ),
      },
      {
        name: '06-assessments.csv',
        data: rowsToCsv(
          applications.flatMap((application) =>
            application.candidateAssessments.map((item) => ({
              Candidate: `${application.candidate.legalFirstName} ${application.candidate.lastName}`,
              Assessment: item.assessment.title,
              Type: item.assessment.type,
              Status: item.status,
              Score: item.score ?? '',
              Passed: item.passed ?? '',
              Submitted: item.submittedAt,
            }))
          )
        ),
      },
      {
        name: '07-interviews.csv',
        data: rowsToCsv(
          applications.flatMap((application) =>
            application.interviews.map((item) => ({
              Candidate: `${application.candidate.legalFirstName} ${application.candidate.lastName}`,
              Interview: item.title,
              Format: item.format,
              Status: item.status,
              Start: item.scheduledStart,
              'Panel members': item.panelMembers.length,
              'Submitted scores': item.panelSubmissions.length,
            }))
          )
        ),
      },
      {
        name: '08-references.csv',
        data: rowsToCsv(
          applications.flatMap((application) =>
            application.referees.map((item) => ({
              Candidate: `${application.candidate.legalFirstName} ${application.candidate.lastName}`,
              Referee: item.name,
              Organization: item.organization,
              Relationship: item.relationship,
              Status: item.requests.at(-1)?.status || 'NOT_SENT',
              Outcome: item.requests.at(-1)?.response?.outcome || '',
            }))
          )
        ),
      },
      {
        name: '09-selection-and-offers.csv',
        data: rowsToCsv(
          applications.flatMap((application) => [
            ...application.selectionDecisions.map((item) => ({
              Candidate: `${application.candidate.legalFirstName} ${application.candidate.lastName}`,
              Record: 'SELECTION',
              Outcome: item.outcome,
              Rank: item.rank ?? '',
              Status: item.approvedAt ? 'APPROVED' : 'PENDING',
              Date: item.approvedAt || '',
            })),
            ...application.offers.map((item) => ({
              Candidate: `${application.candidate.legalFirstName} ${application.candidate.lastName}`,
              Record: 'OFFER',
              Outcome: item.status,
              Rank: '',
              Status: item.status,
              Date: item.sentAt || item.acceptedAt || item.declinedAt || '',
            })),
          ])
        ),
      },
      {
        name: '10-preboarding-and-handover.csv',
        data: rowsToCsv(
          applications.map((application) => ({
            Candidate: `${application.candidate.legalFirstName} ${application.candidate.lastName}`,
            Preboarding: application.preboardings[0]?.status || 'NOT_STARTED',
            Readiness: application.preboardings[0]?.readinessStatus || '',
            Completion: application.preboardings[0]
              ? `${application.preboardings[0].overallCompletionPercentage}%`
              : '',
            'Readiness checks passed':
              application.preboardings[0]?.readinessChecks.filter((item) => ['PASSED', 'WAIVED'].includes(item.status))
                .length || 0,
            Resumption: application.resumptionRecord?.outcome || '',
            'ERP personnel number': application.erpTransferRecord?.erpPersonnelNumber || '',
          }))
        ),
      },
    ]
    const archive = zipEntries(files)
    await logAudit({
      actorUserId: user.userId,
      action: 'VACANCY_DOCUMENTATION_EXPORTED',
      resourceType: 'Vacancy',
      resourceId: vacancy.id,
      newValue: { applications: applications.length, archiveEntries: files.length },
    })
    return new Response(new Uint8Array(archive), {
      headers: {
        'Content-Type': 'application/zip',
        'Content-Disposition': `attachment; filename="frad-vacancy-${safeExportName(vacancy.referenceNumber)}.zip"`,
        'Cache-Control': 'private, no-store',
      },
    })
  } catch (error) {
    return authzResponse(error)
  }
}
